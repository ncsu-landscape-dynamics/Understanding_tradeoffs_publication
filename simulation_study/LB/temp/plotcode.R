parf1 <- function(pm, pcm) {
  parameters = NULL
  parameters = 
    MASS::mvrnorm(1000, pm, pcm) #parameter_means, parameter_cov_matrix)
  
  while (any(
    parameters[1] < 0 |
    parameters[2] <= 0 |
    parameters[3] > 1 |
    parameters[3] <= 0 |
    parameters[4] <= 0 |
    parameters[5] < 0 |
    parameters[6] < 0)) {
    number_of_draws <-
      nrow(parameters[parameters[1] < 0 |
                        parameters[2] <= 0 |
                        parameters[3] > 1 |
                        parameters[3] <= 0 |
                        parameters[4] <= 0 |
                        parameters[5] < 0 |
                        parameters[6] < 0])
    
    if (is.null(number_of_draws)) {
      number_of_draws <- 1
    }
    
    parameters[parameters[1] < 0 |
                 parameters[2] <= 0 |
                 parameters[3] > 1 |
                 parameters[3] <= 0 |
                 parameters[4] <= 0 |
                 parameters[5] < 0 |
                 parameters[6] < 0] <-
      MASS::mvrnorm(number_of_draws,
                    pm, #parameter_means,
                    pcm) #parameter_cov_matrix)
    
  }
  return(parameters)
  number_of_draws = NULL
}

bareminf <- function(pc, pcm) {
  parameters = MASS::mvrnorm(1000, pc, pcm)
  return(parameters)
}

